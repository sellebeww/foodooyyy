// scripts/seed.ts
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  generateScenarioHistory,
  type DemoScenario,
} from "../src/demo/generator.ts";
import { DEMO_SCENARIO_IDS } from "../src/demo/catalog.ts";
import { demoScenario } from "../src/demo/scenarios.ts";
import { profileHours } from "../src/domain/setup.ts";
import { criticalRatio, suggestQty } from "../src/domain/suggest.ts";
import { spansMidnight, weekdayOf } from "../src/domain/time.ts";

const REFERENCE_DATE = "2026-12-01";
const WEEKDAYS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
const LEVELS: Record<number, string> = { 1: "quiet", 2: "normal", 4: "busy" };

const rootUrl = new URL("../", import.meta.url);
const outputPath = fileURLToPath(new URL("docs/DEMO_SCENARIOS.md", rootUrl));

const PURPOSE: Record<number, string> = {
  1: "Morning stall with two rush hours. Nasi Uduk is cooked well below demand, so it sells out on most days and shows the sold-out demand correction.",
  2: "Office lunch stall with one sharp noon peak. Weekdays are busy and weekends are quiet, so suggestions use same-weekday history (Saturday and Monday get different numbers).",
  3: "Night stall open from 18:00 to 02:00. The stall day crosses midnight, which exercises the stall-date rollover (D-080).",
  4: "Stall that opened four days ago. There is not enough history yet, so every suggestion is a cold start: Lontong Sayur goes up (sold out), Nasi Campur goes down (leftovers). Bakwan has a salvage value.",
};

function rupiah(value: number): string {
  return `Rp ${value.toLocaleString("de-DE")}`;
}

function table(headers: string[], rows: string[][]): string {
  const widths = headers.map((header, column) =>
    Math.max(
      3,
      header.length,
      ...rows.map((row) => (row[column] as string).length),
    ),
  );
  const line = (cells: string[]): string =>
    `| ${cells.map((cell, column) => cell.padEnd(widths[column] as number)).join(" | ")} |`;
  return [
    line(headers),
    line(widths.map((width) => "-".repeat(width))),
    ...rows.map(line),
  ].join("\n");
}

function section(scenario: DemoScenario): string {
  const history = generateScenarioHistory(REFERENCE_DATE, scenario);
  const weekday = weekdayOf(REFERENCE_DATE);
  const unusual = history.days.filter((day) => day.unusual).length;
  const settings = history.settings;
  const busy = profileHours(settings.openAt, settings.closeAt)
    .map((hour) => {
      const level = settings.busyProfile[hour] ?? 2;
      return `${hour}=${LEVELS[level] ?? String(level)}`;
    })
    .join(", ");

  const menuRows = history.menus.map((menu) => [
    menu.name,
    rupiah(menu.price),
    rupiah(menu.cost),
    rupiah(menu.salvage),
    String(menu.usualQty),
    String(scenario.trueMeans[menu.id] as number),
    criticalRatio(menu).toFixed(2),
  ]);

  const historyRows = history.menus.map((menu) => {
    const rows = history.menuDays.filter((row) => row.menuId === menu.id);
    const soldOut = rows.filter((row) => row.soldOutAt !== null).length;
    const leftover = rows.reduce((sum, row) => sum + (row.leftover ?? 0), 0);
    const suggestion = suggestQty(
      menu,
      weekday,
      history.menuDays,
      history.days,
    );
    return [
      menu.name,
      String(soldOut),
      String(rows.length - soldOut),
      String(leftover),
      String(suggestion.qty),
      `${suggestion.reason.code} (${suggestion.reason.scope}, ${suggestion.reason.observations} days)`,
    ];
  });

  return `## Scenario ${scenario.id}: ${scenario.stallName}

${PURPOSE[scenario.id] ?? ""}

- Hours: ${settings.openAt} to ${settings.closeAt}${spansMidnight(settings) ? " (crosses midnight)" : ""}
- Busy hours: ${busy}
- Weekday demand factors (Sun to Sat): ${scenario.weekdayFactors.map((factor, day) => `${WEEKDAYS[day] as string} ${factor}`).join(", ")}
- History: ${scenario.historyDays} closed days, ${unusual} marked unusual
- Seed: \`${scenario.seed}\`

${table(["Menu", "Price", "Cost", "Salvage", "Usual", "True mean", "Critical ratio"], menuRows)}

${table(["Menu", "Sold-out days", "Leftover days", "Leftover portions", `Suggestion for ${REFERENCE_DATE}`, "Reason"], historyRows)}
`;
}

const report = `# Demo scenarios

Generated by \`npm run seed\` from \`src/demo/\`. Do not edit by hand.

**All four stalls are synthetic demo data.** They are labelled "Demo data" in the app. The "true mean" is the generator's hidden demand; it is never stored in the app.

In the app, **Try demo stall** (first screen) and **Settings → Choose another demo stall** offer all four. Each history always ends the day before the stall day it is loaded or opened on: when the app is opened on a later day, the demo is generated again with the same scenario, so the content stays the same and only the dates move. \`VITE_DEMO=off\` in \`.env\` hides the demo; empty or \`on\` shows it (see \`.env.example\`).

The history below ends the day before ${REFERENCE_DATE} (${WEEKDAYS[weekdayOf(REFERENCE_DATE)] as string}). In the app the dates follow the current day, and because demand depends on the weekday, the numbers there differ slightly.

${DEMO_SCENARIO_IDS.map((id) => section(demoScenario(id))).join("\n")}`;

writeFileSync(outputPath, report);
console.log(`Wrote ${outputPath}`);
